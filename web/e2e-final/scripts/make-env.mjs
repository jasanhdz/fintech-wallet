#!/usr/bin/env node
// Generates `.env.web-final` (ignored by `.env.*`) with random local-only secrets.
// Idempotent: keeps an existing file unless `--force`. Never prints secret values.
import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, writeFileSync } from 'node:fs';
import { DB_PORT, ENV_FILE } from './env-lib.mjs';

const force = process.argv.includes('--force');
if (existsSync(ENV_FILE) && !force) {
  console.log(`make-env: ${ENV_FILE} already exists (kept). Use --force to regenerate.`);
  process.exit(0);
}

const b64 = (bytes) => randomBytes(bytes).toString('base64');
const lines = [
  '# Generated by web/e2e-final/scripts/make-env.mjs. Local-only, isolated web-fidelity-final environment.',
  '# Every *DATABASE_URL* targets the private container on 127.0.0.1:55433 (wallet_test).',
  `WEB_PG_SUPERUSER_PASSWORD=${randomBytes(24).toString('hex')}`,
  `TEST_DATABASE_URL=postgres://wallet_runtime_test:test_runtime_local_only@127.0.0.1:${DB_PORT}/wallet_test`,
  `TEST_MIGRATOR_DATABASE_URL=postgres://wallet_migrator_test:test_migrator_local_only@127.0.0.1:${DB_PORT}/wallet_test`,
  `DATABASE_URL=postgres://wallet_runtime_test:test_runtime_local_only@127.0.0.1:${DB_PORT}/wallet_test`,
  'MIGRATOR_DATABASE_URL=postgres://none@127.0.0.1:1/none',
  `JWT_ACCESS_SECRET=${b64(48)}`,
  `REFRESH_TOKEN_PEPPER=${b64(32)}`,
  `CLABE_ENCRYPTION_KEY=${b64(32)}`,
  `CLABE_LOOKUP_KEY=${b64(32)}`,
  '',
];
writeFileSync(ENV_FILE, lines.join('\n'), { mode: 0o600 });
chmodSync(ENV_FILE, 0o600);
console.log(`make-env: wrote ${ENV_FILE} (secrets not printed).`);
